func (a *app) handleUserByName(w http.ResponseWriter, r *http.Request) {
	username, ok := parseStringPath(w, r.URL.Path, "/user/")
	if !ok {
		return
	}

	switch r.Method {
	case http.MethodGet:
		user, err := a.getUser(r.Context(), username)
		if errors.Is(err, sql.ErrNoRows) {
			errorJSON(w, http.StatusNotFound, "user not found")
			return
		}
		if err != nil {
			errorJSON(w, http.StatusInternalServerError, "database error")
			return
		}
		writeJSON(w, http.StatusOK, user)
	case http.MethodPut:
		a.updateUser(w, r, username)
	case http.MethodDelete:
		res, err := a.db.ExecContext(r.Context(), `DELETE FROM users WHERE username = $1`, username)
		if err != nil {
			errorJSON(w, http.StatusInternalServerError, "database error")
			return
		}
		count, err := res.RowsAffected()
		if err != nil {
			errorJSON(w, http.StatusInternalServerError, "database error")
			return
		}
		if count == 0 {
			errorJSON(w, http.StatusNotFound, "user not found")
			return
		}
		writeJSON(w, http.StatusOK, map[string]string{"message": "user deleted"})
	default:
		methodNotAllowed(w, "GET, PUT, DELETE")
	}
}

func (a *app) getUser(ctx context.Context, username string) (User, error) {
	return scanUser(a.db.QueryRowContext(ctx, `
		SELECT id, username, first_name, last_name, email, password, phone, user_status
		FROM users
		WHERE username = $1`, username))
}

func (a *app) updateUser(w http.ResponseWriter, r *http.Request, pathUsername string) {
	var user User
	if !decodeJSON(w, r, &user) {
		return
	}
	if user.Username == "" {
		user.Username = pathUsername
	}

	user, err := scanUser(a.db.QueryRowContext(r.Context(), `
		UPDATE users
		SET username = $2,
			first_name = $3,
			last_name = $4,
			email = $5,
			password = $6,
			phone = $7,
			user_status = $8,
			updated_at = now()
		WHERE username = $1
		RETURNING id, username, first_name, last_name, email, password, phone, user_status`,
		pathUsername, user.Username, user.FirstName, user.LastName, user.Email, user.Password, user.Phone, user.UserStatus))
	if errors.Is(err, sql.ErrNoRows) {
		errorJSON(w, http.StatusNotFound, "user not found")
		return
	}
	if err != nil {
		errorJSON(w, http.StatusBadRequest, "invalid input")
		return
	}
	writeJSON(w, http.StatusOK, user)
}

func (a *app) loginUser(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet {
		methodNotAllowed(w, "GET")
		return
	}
	query := r.URL.Query()
	username := query.Get("username")
	password := query.Get("password")
	if username == "" || password == "" {
		errorJSON(w, http.StatusBadRequest, "invalid credentials")
		return
	}

	var storedPassword string
	err := a.db.QueryRowContext(r.Context(), `SELECT password FROM users WHERE username = $1`, username).Scan(&storedPassword)
	if err != nil || storedPassword != password {
		errorJSON(w, http.StatusBadRequest, "invalid credentials")
		return
	}
	writeJSON(w, http.StatusOK, "logged in user "+username)
}

func scanPet(row *sql.Row) (Pet, error) {
	var pet Pet
	err := row.Scan(&pet.ID, &pet.Name, pq.Array(&pet.PhotoURLs), &pet.Status)
	return pet, err
}

func scanOrder(row *sql.Row) (Order, error) {
	var order Order
	var shipDate sql.NullTime
	err := row.Scan(&order.ID, &order.PetID, &order.Quantity, &shipDate, &order.Status, &order.Complete)
	if shipDate.Valid {
		order.ShipDate = &shipDate.Time
	}
	return order, err
}

func scanUser(row *sql.Row) (User, error) {
	var user User
	err := row.Scan(&user.ID, &user.Username, &user.FirstName, &user.LastName, &user.Email, &user.Password, &user.Phone, &user.UserStatus)
	return user, err
}

func deleteByID(ctx context.Context, db *sql.DB, table string, id int64) (bool, error) {
	res, err := db.ExecContext(ctx, "DELETE FROM "+table+" WHERE id = $1", id)
	if err != nil {
		return false, err
	}
	count, err := res.RowsAffected()
	if err != nil {
		return false, err
	}
	return count > 0, nil
}

func validatePet(pet Pet) error {
	if pet.Name == "" {
		return errors.New("name is required")
	}
	if pet.PhotoURLs == nil {
		return errors.New("photoUrls is required")
	}
	if !validPetStatusOrEmpty(pet.Status) {
		return errors.New("invalid pet status")
	}
	return nil
}

func validPetStatusOrEmpty(status string) bool {
	return status == "" || validPetStatus(status)
}

func validPetStatus(status string) bool {
	switch status {
	case "available", "pending", "sold":
		return true
	default:
		return false
	}
}

func validOrderStatusOrEmpty(status string) bool {
	switch status {
	case "", "placed", "approved", "delivered":
		return true
	default:
		return false
	}
}

func parseIDPath(w http.ResponseWriter, pathValue, prefix string) (int64, bool) {
	part := strings.TrimPrefix(pathValue, prefix)
	if part == "" || strings.Contains(part, "/") {
		errorJSON(w, http.StatusNotFound, "not found")
		return 0, false
	}
	id, err := strconv.ParseInt(part, 10, 64)
	if err != nil || id <= 0 {
		errorJSON(w, http.StatusBadRequest, "invalid id")
		return 0, false
	}
	return id, true
}

func parseStringPath(w http.ResponseWriter, pathValue, prefix string) (string, bool) {
	part := strings.TrimPrefix(pathValue, prefix)
	if part == "" || strings.Contains(part, "/") {
		errorJSON(w, http.StatusNotFound, "not found")
		return "", false
	}
	decoded, err := url.PathUnescape(part)
	if err != nil || decoded == "" {
		errorJSON(w, http.StatusBadRequest, "invalid path")
		return "", false
	}
	return decoded, true
}

func decodeJSON(w http.ResponseWriter, r *http.Request, dst any) bool {
	r.Body = http.MaxBytesReader(w, r.Body, maxRequestBodyBytes)
	dec := json.NewDecoder(r.Body)
	if err := dec.Decode(dst); err != nil {
		errorJSON(w, http.StatusBadRequest, "invalid JSON")
		return false
	}
	return true
}

func writeJSON(w http.ResponseWriter, status int, value any) {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(status)
	if err := json.NewEncoder(w).Encode(value); err != nil {
		log.Printf("failed to encode response: %v", err)
	}
}

func errorJSON(w http.ResponseWriter, status int, message string) {
	writeJSON(w, status, map[string]string{"error": message})
}

func methodNotAllowed(w http.ResponseWriter, allow string) {
	w.Header().Set("Allow", allow)
	errorJSON(w, http.StatusMethodNotAllowed, "method not allowed")
}
