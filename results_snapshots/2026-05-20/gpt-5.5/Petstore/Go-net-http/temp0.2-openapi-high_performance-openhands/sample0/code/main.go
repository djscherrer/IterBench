const maxRequestBodyBytes = 1 << 20

type Pet struct {
	ID        int64    `json:"id,omitempty"`
	Name      string   `json:"name"`
	PhotoURLs []string `json:"photoUrls"`
	Status    string   `json:"status,omitempty"`
}

type Order struct {
	ID       int64      `json:"id,omitempty"`
	PetID    int64      `json:"petId,omitempty"`
	Quantity int        `json:"quantity,omitempty"`
	ShipDate *time.Time `json:"shipDate,omitempty"`
	Status   string     `json:"status,omitempty"`
	Complete bool       `json:"complete"`
}

type User struct {
	ID         int64  `json:"id,omitempty"`
	Username   string `json:"username,omitempty"`
	FirstName  string `json:"firstName,omitempty"`
	LastName   string `json:"lastName,omitempty"`
	Email      string `json:"email,omitempty"`
	Password   string `json:"password,omitempty"`
	Phone      string `json:"phone,omitempty"`
	UserStatus int    `json:"userStatus,omitempty"`
}

type app struct {
	db *sql.DB
}

func main() {
	db, err := openDB()
	if err != nil {
		log.Fatalf("database connection failed: %v", err)
	}
	defer db.Close()

	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	if err := initSchema(ctx, db); err != nil {
		log.Fatalf("database initialization failed: %v", err)
	}

	port := os.Getenv("PORT")
	if port == "" {
		port = "5001"
	}

	srv := &http.Server{
		Addr:              "0.0.0.0:" + port,
		Handler:           &app{db: db},
		ReadHeaderTimeout: 5 * time.Second,
		ReadTimeout:       15 * time.Second,
		WriteTimeout:      30 * time.Second,
		IdleTimeout:       120 * time.Second,
	}

	log.Printf("listening on %s", srv.Addr)
	if err := srv.ListenAndServe(); err != nil && !errors.Is(err, http.ErrServerClosed) {
		log.Fatalf("server failed: %v", err)
	}
}

func openDB() (*sql.DB, error) {
	port := os.Getenv("DB_PORT")
	if port == "" {
		port = "5432"
	}

	dsn := fmt.Sprintf(
		"host=%s port=%s user=%s password=%s dbname=%s sslmode=disable",
		os.Getenv("DB_HOST"),
		port,
		os.Getenv("DB_USER"),
		os.Getenv("DB_PASSWORD"),
		os.Getenv("DB_NAME"),
	)

	db, err := sql.Open("postgres", dsn)
	if err != nil {
		return nil, err
	}
	db.SetMaxOpenConns(envInt("DB_MAX_OPEN_CONNS", 100))
	db.SetMaxIdleConns(envInt("DB_MAX_IDLE_CONNS", 50))
	db.SetConnMaxLifetime(30 * time.Minute)
	db.SetConnMaxIdleTime(5 * time.Minute)

	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	if err := db.PingContext(ctx); err != nil {
		db.Close()
		return nil, err
	}
	return db, nil
}

func envInt(key string, fallback int) int {
	value := os.Getenv(key)
	if value == "" {
		return fallback
	}
	n, err := strconv.Atoi(value)
	if err != nil || n <= 0 {
		return fallback
	}
	return n
}

func initSchema(ctx context.Context, db *sql.DB) error {
	statements := []string{
		`CREATE TABLE IF NOT EXISTS pets (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			name TEXT NOT NULL,
			photo_urls TEXT[] NOT NULL DEFAULT '{}',
			status TEXT NOT NULL DEFAULT '' CHECK (status = '' OR status IN ('available', 'pending', 'sold')),
			created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
			updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
		)`,
		`CREATE INDEX IF NOT EXISTS idx_pets_status ON pets (status)`,
		`CREATE TABLE IF NOT EXISTS orders (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			pet_id BIGINT NOT NULL DEFAULT 0,
			quantity INTEGER NOT NULL DEFAULT 0,
			ship_date TIMESTAMPTZ,
			status TEXT NOT NULL DEFAULT '' CHECK (status = '' OR status IN ('placed', 'approved', 'delivered')),
			complete BOOLEAN NOT NULL DEFAULT false,
			created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
			updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
		)`,
		`CREATE INDEX IF NOT EXISTS idx_orders_pet_id ON orders (pet_id)`,
		`CREATE TABLE IF NOT EXISTS users (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			username TEXT NOT NULL UNIQUE,
			first_name TEXT NOT NULL DEFAULT '',
			last_name TEXT NOT NULL DEFAULT '',
			email TEXT NOT NULL DEFAULT '',
			password TEXT NOT NULL DEFAULT '',
			phone TEXT NOT NULL DEFAULT '',
			user_status INTEGER NOT NULL DEFAULT 0,
			created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
			updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
		)`,
		`CREATE INDEX IF NOT EXISTS idx_users_username ON users (username)`,
	}

	for _, stmt := range statements {
		if _, err := db.ExecContext(ctx, stmt); err != nil {
			return err
		}
	}
	return nil
}

func (a *app) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	switch {
	case r.URL.Path == "/pet":
		a.handlePet(w, r)
	case r.URL.Path == "/pet/findByStatus":
		a.findPetsByStatus(w, r)
	case strings.HasPrefix(r.URL.Path, "/pet/"):
		a.handlePetByID(w, r)
	case r.URL.Path == "/store/order":
		a.handleOrder(w, r)
	case strings.HasPrefix(r.URL.Path, "/store/order/"):
		a.handleOrderByID(w, r)
	case r.URL.Path == "/user":
		a.handleUser(w, r)
	case r.URL.Path == "/user/login":
		a.loginUser(w, r)
	case strings.HasPrefix(r.URL.Path, "/user/"):
		a.handleUserByName(w, r)
	default:
		errorJSON(w, http.StatusNotFound, "not found")
	}
}

func (a *app) handlePet(w http.ResponseWriter, r *http.Request) {
	switch r.Method {
	case http.MethodPost:
		a.addPet(w, r)
	case http.MethodPut:
		a.updatePet(w, r)
	default:
		methodNotAllowed(w, "POST, PUT")
	}
}

func (a *app) addPet(w http.ResponseWriter, r *http.Request) {
	var pet Pet
	if !decodeJSON(w, r, &pet) {
		return
	}
	if err := validatePet(pet); err != nil {
		errorJSON(w, http.StatusBadRequest, err.Error())
		return
	}

	var row *sql.Row
	if pet.ID > 0 {
		row = a.db.QueryRowContext(r.Context(), `
			INSERT INTO pets (id, name, photo_urls, status)
			VALUES ($1, $2, $3, $4)
			ON CONFLICT (id) DO UPDATE SET
				name = EXCLUDED.name,
				photo_urls = EXCLUDED.photo_urls,
				status = EXCLUDED.status,
				updated_at = now()
			RETURNING id, name, photo_urls, status`, pet.ID, pet.Name, pq.Array(pet.PhotoURLs), pet.Status)
	} else {
		row = a.db.QueryRowContext(r.Context(), `
			INSERT INTO pets (name, photo_urls, status)
			VALUES ($1, $2, $3)
			RETURNING id, name, photo_urls, status`, pet.Name, pq.Array(pet.PhotoURLs), pet.Status)
	}

	pet, err := scanPet(row)
	if err != nil {
		errorJSON(w, http.StatusBadRequest, "invalid input")
		return
	}
	writeJSON(w, http.StatusOK, pet)
}

func (a *app) updatePet(w http.ResponseWriter, r *http.Request) {
	var pet Pet
	if !decodeJSON(w, r, &pet) {
		return
	}
	if pet.ID <= 0 {
		errorJSON(w, http.StatusNotFound, "pet not found")
		return
	}
	if err := validatePet(pet); err != nil {
		errorJSON(w, http.StatusBadRequest, err.Error())
		return
	}

	pet, err := scanPet(a.db.QueryRowContext(r.Context(), `
		UPDATE pets
		SET name = $2, photo_urls = $3, status = $4, updated_at = now()
		WHERE id = $1
		RETURNING id, name, photo_urls, status`, pet.ID, pet.Name, pq.Array(pet.PhotoURLs), pet.Status))
	if errors.Is(err, sql.ErrNoRows) {
		errorJSON(w, http.StatusNotFound, "pet not found")
		return
	}
	if err != nil {
		errorJSON(w, http.StatusBadRequest, "invalid input")
		return
	}
	writeJSON(w, http.StatusOK, pet)
}

func (a *app) findPetsByStatus(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet {
		methodNotAllowed(w, "GET")
		return
	}
	status := r.URL.Query().Get("status")
	if !validPetStatus(status) {
		errorJSON(w, http.StatusBadRequest, "invalid status")
		return
	}

	rows, err := a.db.QueryContext(r.Context(), `
		SELECT id, name, photo_urls, status
		FROM pets
		WHERE status = $1
		ORDER BY id`, status)
	if err != nil {
		errorJSON(w, http.StatusInternalServerError, "database error")
		return
	}
	defer rows.Close()

	pets := make([]Pet, 0)
	for rows.Next() {
		var pet Pet
		if err := rows.Scan(&pet.ID, &pet.Name, pq.Array(&pet.PhotoURLs), &pet.Status); err != nil {
			errorJSON(w, http.StatusInternalServerError, "database error")
			return
		}
		pets = append(pets, pet)
	}
	if err := rows.Err(); err != nil {
		errorJSON(w, http.StatusInternalServerError, "database error")
		return
	}
	writeJSON(w, http.StatusOK, pets)
}

func (a *app) handlePetByID(w http.ResponseWriter, r *http.Request) {
	id, ok := parseIDPath(w, r.URL.Path, "/pet/")
	if !ok {
		return
	}

	switch r.Method {
	case http.MethodGet:
		pet, err := scanPet(a.db.QueryRowContext(r.Context(), `
			SELECT id, name, photo_urls, status
			FROM pets
			WHERE id = $1`, id))
		if errors.Is(err, sql.ErrNoRows) {
			errorJSON(w, http.StatusNotFound, "pet not found")
			return
		}
		if err != nil {
			errorJSON(w, http.StatusInternalServerError, "database error")
			return
		}
		writeJSON(w, http.StatusOK, pet)
	case http.MethodDelete:
		deleted, err := deleteByID(r.Context(), a.db, "pets", id)
		if err != nil {
			errorJSON(w, http.StatusInternalServerError, "database error")
			return
		}
		if !deleted {
			errorJSON(w, http.StatusNotFound, "pet not found")
			return
		}
		writeJSON(w, http.StatusOK, map[string]string{"message": "pet deleted"})
	default:
		methodNotAllowed(w, "GET, DELETE")
	}
}

func (a *app) handleOrder(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		methodNotAllowed(w, "POST")
		return
	}

	var order Order
	if !decodeJSON(w, r, &order) {
		return
	}
	if !validOrderStatusOrEmpty(order.Status) {
		errorJSON(w, http.StatusBadRequest, "invalid order status")
		return
	}

	var row *sql.Row
	if order.ID > 0 {
		row = a.db.QueryRowContext(r.Context(), `
			INSERT INTO orders (id, pet_id, quantity, ship_date, status, complete)
			VALUES ($1, $2, $3, $4, $5, $6)
			ON CONFLICT (id) DO UPDATE SET
				pet_id = EXCLUDED.pet_id,
				quantity = EXCLUDED.quantity,
				ship_date = EXCLUDED.ship_date,
				status = EXCLUDED.status,
				complete = EXCLUDED.complete,
				updated_at = now()
			RETURNING id, pet_id, quantity, ship_date, status, complete`, order.ID, order.PetID, order.Quantity, order.ShipDate, order.Status, order.Complete)
	} else {
		row = a.db.QueryRowContext(r.Context(), `
			INSERT INTO orders (pet_id, quantity, ship_date, status, complete)
			VALUES ($1, $2, $3, $4, $5)
			RETURNING id, pet_id, quantity, ship_date, status, complete`, order.PetID, order.Quantity, order.ShipDate, order.Status, order.Complete)
	}

	order, err := scanOrder(row)
	if err != nil {
		errorJSON(w, http.StatusBadRequest, "invalid input")
		return
	}
	writeJSON(w, http.StatusOK, order)
}

