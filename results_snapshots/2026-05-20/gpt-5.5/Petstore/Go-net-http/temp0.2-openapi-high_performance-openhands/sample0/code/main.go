func (a *app) handleUser(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		methodNotAllowed(w, "POST")
		return
	}

	var user User
	if !decodeJSON(w, r, &user) {
		return
	}
	if user.Username == "" {
		errorJSON(w, http.StatusBadRequest, "username is required")
		return
	}

	user, err := a.createOrReplaceUser(r.Context(), user)
	if err != nil {
		errorJSON(w, http.StatusBadRequest, "invalid input")
		return
	}
	writeJSON(w, http.StatusOK, user)
}

