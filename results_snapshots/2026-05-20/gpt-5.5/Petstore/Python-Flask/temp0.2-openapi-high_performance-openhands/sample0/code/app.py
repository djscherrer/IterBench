import os
from contextlib import contextmanager

import psycopg2
from psycopg2 import pool
from psycopg2.extras import RealDictCursor
from flask import Flask, jsonify, request


PET_STATUSES = {"available", "pending", "sold"}
ORDER_STATUSES = {"placed", "approved", "delivered"}
DB_LOCK_KEY_1 = 739214
DB_LOCK_KEY_2 = 108397

app = Flask(__name__)
app.json.sort_keys = False

_connection_pool = None
_connection_pool_pid = None


def _db_config():
    return {
        "host": os.environ.get("DB_HOST"),
        "port": int(os.environ.get("DB_PORT", "5432")),
        "user": os.environ.get("DB_USER"),
        "password": os.environ.get("DB_PASSWORD"),
        "dbname": os.environ.get("DB_NAME"),
        "connect_timeout": 5,
        "application_name": "petstore_api",
    }


def _connect():
    return psycopg2.connect(**_db_config())


def init_db():
    conn = _connect()
    try:
        conn.autocommit = True
        with conn.cursor() as cur:
            cur.execute("SELECT pg_advisory_lock(%s, %s)", (DB_LOCK_KEY_1, DB_LOCK_KEY_2))
            try:
                cur.execute(
                    """
                    CREATE TABLE IF NOT EXISTS pets (
                        id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                        name TEXT NOT NULL,
                        photo_urls TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
                        status TEXT CHECK (status IS NULL OR status IN ('available', 'pending', 'sold'))
                    )
                    """
                )
                cur.execute("CREATE INDEX IF NOT EXISTS idx_pets_status ON pets (status)")
                cur.execute(
                    """
                    CREATE TABLE IF NOT EXISTS orders (
                        id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                        pet_id BIGINT,
                        quantity INTEGER,
                        ship_date TIMESTAMPTZ,
                        status TEXT CHECK (status IS NULL OR status IN ('placed', 'approved', 'delivered')),
                        complete BOOLEAN
                    )
                    """
                )
                cur.execute("CREATE INDEX IF NOT EXISTS idx_orders_pet_id ON orders (pet_id)")
                cur.execute(
                    """
                    CREATE TABLE IF NOT EXISTS users (
                        id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                        username TEXT UNIQUE,
                        first_name TEXT,
                        last_name TEXT,
                        email TEXT,
                        password TEXT,
                        phone TEXT,
                        user_status INTEGER
                    )
                    """
                )
                cur.execute("CREATE INDEX IF NOT EXISTS idx_users_username ON users (username)")
                sync_identity_sequence(cur, "pets", "pets_id_seq")
                sync_identity_sequence(cur, "orders", "orders_id_seq")
                sync_identity_sequence(cur, "users", "users_id_seq")
            finally:
                cur.execute("SELECT pg_advisory_unlock(%s, %s)", (DB_LOCK_KEY_1, DB_LOCK_KEY_2))
    finally:
        conn.close()


def get_pool():
    global _connection_pool, _connection_pool_pid
    pid = os.getpid()
    if _connection_pool is None or _connection_pool_pid != pid:
        if _connection_pool is not None:
            try:
                _connection_pool.closeall()
            except Exception:
                pass
        maxconn = max(1, int(os.environ.get("DB_POOL_MAX", "8")))
        _connection_pool = pool.ThreadedConnectionPool(1, maxconn, **_db_config())
        _connection_pool_pid = pid
    return _connection_pool


@contextmanager
def db_connection():
    conn = get_pool().getconn()
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        get_pool().putconn(conn)


def sync_identity_sequence(cur, table, sequence):
    cur.execute(
        f"""
        SELECT CASE
                 WHEN max_id > last_value
                 THEN setval(pg_get_serial_sequence('{table}', 'id'), max_id, true)
                 ELSE last_value
               END
          FROM (SELECT COALESCE(MAX(id), 0) AS max_id FROM {table}) AS table_state,
               {sequence}
        """
    )



def error_response(message, status_code):
    return jsonify({"error": message}), status_code


def json_body():
    data = request.get_json(silent=True)
    if not isinstance(data, dict):
        return None, (jsonify({"error": "Invalid JSON body"}), 400)
    return data, None


def require_int(value, field):
    if value is None:
        return None, None
    if isinstance(value, bool):
        return None, f"{field} must be an integer"
    try:
        return int(value), None
    except (TypeError, ValueError):
        return None, f"{field} must be an integer"


def require_string(value, field, required=False):
    if value is None:
        if required:
            return None, f"{field} is required"
        return None, None
    if not isinstance(value, str):
        return None, f"{field} must be a string"
    return value, None


def require_bool(value, field):
    if value is None:
        return None, None
    if not isinstance(value, bool):
        return None, f"{field} must be a boolean"
    return value, None


def row_to_pet(row):
    return {
        "id": row["id"],
        "name": row["name"],
        "photoUrls": row["photo_urls"] or [],
        "status": row["status"],
    }


def row_to_order(row):
    ship_date = row["ship_date"]
    return {
        "id": row["id"],
        "petId": row["pet_id"],
        "quantity": row["quantity"],
        "shipDate": ship_date.isoformat() if ship_date is not None else None,
        "status": row["status"],
        "complete": row["complete"],
    }


def row_to_user(row):
    return {
        "id": row["id"],
        "username": row["username"],
        "firstName": row["first_name"],
        "lastName": row["last_name"],
        "email": row["email"],
        "password": row["password"],
        "phone": row["phone"],
        "userStatus": row["user_status"],
    }


def validate_pet(data, partial=False):
    pet_id, err = require_int(data.get("id"), "id")
    if err:
        return None, err
    name, err = require_string(data.get("name"), "name", required=not partial)
    if err:
        return None, err
    photo_urls = data.get("photoUrls")
    if photo_urls is None:
        if not partial:
            return None, "photoUrls is required"
    elif not isinstance(photo_urls, list) or any(not isinstance(item, str) for item in photo_urls):
        return None, "photoUrls must be an array of strings"
    status, err = require_string(data.get("status"), "status")
    if err:
        return None, err
    if status is not None and status not in PET_STATUSES:
        return None, "status must be one of: available, pending, sold"
    return {"id": pet_id, "name": name, "photo_urls": photo_urls, "status": status}, None


def validate_order(data):
    order_id, err = require_int(data.get("id"), "id")
    if err:
        return None, err
    pet_id, err = require_int(data.get("petId"), "petId")
    if err:
        return None, err
    quantity, err = require_int(data.get("quantity"), "quantity")
    if err:
        return None, err
    ship_date = data.get("shipDate")
    if ship_date is not None and not isinstance(ship_date, str):
        return None, "shipDate must be a string"
    status, err = require_string(data.get("status"), "status")
    if err:
        return None, err
    if status is not None and status not in ORDER_STATUSES:
        return None, "status must be one of: placed, approved, delivered"
    complete, err = require_bool(data.get("complete"), "complete")
    if err:
        return None, err
    return {
        "id": order_id,
        "pet_id": pet_id,
        "quantity": quantity,
        "ship_date": ship_date,
        "status": status,
        "complete": complete,
    }, None


