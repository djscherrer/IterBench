def insert_pet(pet):
    columns = ["name", "photo_urls", "status"]
    values = [pet["name"], pet["photo_urls"], pet["status"]]
    if pet["id"] is not None:
        columns.insert(0, "id")
        values.insert(0, pet["id"])
    placeholders = ", ".join(["%s"] * len(columns))
    cols = ", ".join(columns)
    update_cols = ", ".join(f"{col} = EXCLUDED.{col}" for col in columns if col != "id")
    with db_connection() as conn, conn.cursor(cursor_factory=RealDictCursor) as cur:
        cur.execute(
            f"""
            INSERT INTO pets ({cols}) VALUES ({placeholders})
            ON CONFLICT (id) DO UPDATE SET {update_cols}
            RETURNING id, name, photo_urls, status
            """,
            values,
        )
        row = cur.fetchone()
        if pet["id"] is not None:
            sync_identity_sequence(cur, "pets", "pets_id_seq")
        return row_to_pet(row)


@app.post("/pet")
def add_pet():
    data, error = json_body()
    if error:
        return error
    pet, err = validate_pet(data)
    if err:
        return error_response(err, 400)
    try:
        return jsonify(insert_pet(pet)), 200
    except psycopg2.Error:
        app.logger.exception("failed to add pet")
        return error_response("Invalid input", 400)


