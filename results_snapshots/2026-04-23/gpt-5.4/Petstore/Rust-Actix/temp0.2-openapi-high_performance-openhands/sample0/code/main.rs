struct DbSettings {
    host: String,
    port: u16,
    user: String,
    password: String,
    dbname: String,
    pool_size: usize,
}

impl DbSettings {
    fn from_env() -> io::Result<Self> {
        Ok(Self {
            host: env::var("DB_HOST")
                .map_err(|_| io::Error::new(io::ErrorKind::InvalidInput, "DB_HOST is not set"))?,
            port: env::var("DB_PORT")
                .map_err(|_| io::Error::new(io::ErrorKind::InvalidInput, "DB_PORT is not set"))?
                .parse()
                .map_err(|err| io::Error::new(io::ErrorKind::InvalidInput, format!("invalid DB_PORT: {err}")))?,
            user: env::var("DB_USER")
                .map_err(|_| io::Error::new(io::ErrorKind::InvalidInput, "DB_USER is not set"))?,
            password: env::var("DB_PASSWORD")
                .map_err(|_| io::Error::new(io::ErrorKind::InvalidInput, "DB_PASSWORD is not set"))?,
            dbname: env::var("DB_NAME")
                .map_err(|_| io::Error::new(io::ErrorKind::InvalidInput, "DB_NAME is not set"))?,
            pool_size: env::var("DB_POOL_SIZE")
                .ok()
                .and_then(|value| value.parse().ok())
                .unwrap_or_else(default_pool_size),
        })
    }

    fn candidate_hosts(&self) -> Vec<&str> {
        let mut candidates = vec![self.host.as_str()];
        if self.host != "127.0.0.1" {
            candidates.push("127.0.0.1");
        }
        if self.host != "localhost" {
            candidates.push("localhost");
        }
        candidates
    }
}

fn build_pool(settings: &DbSettings, host: &str) -> io::Result<Pool> {
    let mut cfg = PoolConfig::new();
    cfg.host = Some(host.to_owned());
    cfg.port = Some(settings.port);
    cfg.user = Some(settings.user.clone());
    cfg.password = Some(settings.password.clone());
    cfg.dbname = Some(settings.dbname.clone());
    cfg.manager = Some(ManagerConfig {
        recycling_method: RecyclingMethod::Fast,
    });
    cfg.pool = Some(deadpool_postgres::PoolConfig {
        max_size: settings.pool_size,
        ..Default::default()
    });

    cfg.create_pool(Some(Runtime::Tokio1), NoTls)
        .map_err(|err| io::Error::new(io::ErrorKind::Other, err.to_string()))
}

async fn build_initialized_pool() -> io::Result<Pool> {
    let settings = DbSettings::from_env()?;
    let mut last_error = None;

    for host in settings.candidate_hosts() {
        let pool = build_pool(&settings, host)?;
        match init_db(&pool).await {
            Ok(()) => return Ok(pool),
            Err(err) => last_error = Some(io::Error::new(io::ErrorKind::Other, format!("database init failed for host {host}: {err}"))),
        }
    }

    Err(last_error.unwrap_or_else(|| io::Error::new(io::ErrorKind::Other, "database initialization failed")))
}

fn default_pool_size() -> usize {
    std::thread::available_parallelism()
        .map(|parallelism| (parallelism.get() * 4).clamp(16, 128))
        .unwrap_or(32)
}

#[actix_web::main]
async fn main() -> io::Result<()> {
    env_logger::init();

    let pool = build_initialized_pool().await?;

    let state = web::Data::new(AppState { pool });
    let port = env::var("PORT")
        .ok()
        .and_then(|value| value.parse::<u16>().ok())
        .unwrap_or(5001);
    let workers = std::thread::available_parallelism()
        .map(|parallelism| parallelism.get())
        .unwrap_or(4);

    HttpServer::new(move || {
        App::new()
            .wrap(Logger::default())
            .app_data(state.clone())
            .service(
                web::scope("/pet")
                    .route("", web::post().to(add_pet))
                    .route("", web::put().to(update_pet))
                    .route("/findByStatus", web::get().to(find_pets_by_status))
                    .route("/{petId}", web::get().to(get_pet_by_id))
                    .route("/{petId}", web::delete().to(delete_pet)),
            )
            .service(
                web::scope("/store")
                    .route("/order", web::post().to(place_order))
                    .route("/order/{orderId}", web::get().to(get_order_by_id))
                    .route("/order/{orderId}", web::delete().to(delete_order)),
            )
            .service(
                web::scope("/user")
                    .route("", web::post().to(create_user))
                    .route("/login", web::get().to(login_user))
                    .route("/{username}", web::get().to(get_user_by_name))
                    .route("/{username}", web::put().to(update_user))
                    .route("/{username}", web::delete().to(delete_user)),
            )
    })
    .workers(workers)
    .bind(("0.0.0.0", port))?
    .run()
    .await
}
