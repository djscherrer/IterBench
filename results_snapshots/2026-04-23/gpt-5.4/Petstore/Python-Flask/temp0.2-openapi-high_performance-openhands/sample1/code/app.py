import os
import threading
from contextlib import contextmanager
from datetime import datetime

import psycopg2
from psycopg2 import errors
from psycopg2.extras import RealDictCursor
from psycopg2.pool import ThreadedConnectionPool
from flask import Flask, jsonify, request


app = Flask(__name__)
app.config["JSON_SORT_KEYS"] = False

PET_STATUSES = {"available", "pending", "sold"}
ORDER_STATUSES = {"placed", "approved", "delivered"}
DB_INIT_LOCK_ID = 712345678901234567
POOL_MAX_CONNECTIONS = max(4, min(64, (os.cpu_count() or 1) * 4))

_pool = None
_pool_pid = None
_pool_lock = threading.Lock()


class ValidationError(ValueError):
    pass


def load_db_config() -> dict:
    config = {
        "host": os.getenv("DB_HOST"),
        "port": int(os.getenv("DB_PORT", "5432")),
        "user": os.getenv("DB_USER"),
        "password": os.getenv("DB_PASSWORD"),
        "dbname": os.getenv("DB_NAME"),
        "connect_timeout": 5,
        "options": "-c timezone=utc",
    }
    missing = [key.upper() for key, value in config.items() if key in {"host", "user", "password", "dbname"} and not value]
    if missing:
        raise RuntimeError(f"Missing required database environment variables: {', '.join(missing)}")
    return config


DB_CONFIG = load_db_config()


_db_ready = False
_db_init_lock = threading.Lock()


def ensure_database_initialized() -> None:
    global _db_ready
    if _db_ready:
        return
    with _db_init_lock:
        if _db_ready:
            return
        conn = psycopg2.connect(application_name="petstore_api_init", **DB_CONFIG)
        conn.autocommit = True
        try:
            with conn.cursor() as cur:
                cur.execute("SELECT pg_advisory_lock(%s)", (DB_INIT_LOCK_ID,))
                try:
                    cur.execute(
                        """
                        CREATE TABLE IF NOT EXISTS pets (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            name TEXT NOT NULL,
                            photo_urls TEXT[] NOT NULL,
                            status TEXT CHECK (status IN ('available', 'pending', 'sold'))
                        );

                        CREATE INDEX IF NOT EXISTS idx_pets_status ON pets (status);

                        CREATE TABLE IF NOT EXISTS orders (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            pet_id BIGINT,
                            quantity INTEGER,
                            ship_date TIMESTAMPTZ,
                            status TEXT CHECK (status IN ('placed', 'approved', 'delivered')),
                            complete BOOLEAN
                        );

                        CREATE INDEX IF NOT EXISTS idx_orders_pet_id ON orders (pet_id);

                        CREATE TABLE IF NOT EXISTS users (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            username TEXT NOT NULL UNIQUE,
                            first_name TEXT,
                            last_name TEXT,
                            email TEXT,
                            password TEXT,
                            phone TEXT,
                            user_status INTEGER
                        );
                        """
                    )
                finally:
                    cur.execute("SELECT pg_advisory_unlock(%s)", (DB_INIT_LOCK_ID,))
        finally:
            conn.close()
        _db_ready = True


try:
    ensure_database_initialized()
except psycopg2.Error:
    pass


def get_pool() -> ThreadedConnectionPool:
    global _pool, _pool_pid
    ensure_database_initialized()
    current_pid = os.getpid()
    if _pool is None or _pool_pid != current_pid:
        with _pool_lock:
            if _pool is None or _pool_pid != current_pid:
                if _pool is not None:
                    try:
                        _pool.closeall()
                    except Exception:
                        pass
                _pool = ThreadedConnectionPool(
                    minconn=1,
                    maxconn=POOL_MAX_CONNECTIONS,
                    application_name=f"petstore_api_{current_pid}",
                    **DB_CONFIG,
                )
                _pool_pid = current_pid
    return _pool


@contextmanager
def get_cursor():
    pool = get_pool()
    conn = pool.getconn()
    try:
        conn.autocommit = True
        with conn.cursor(cursor_factory=RealDictCursor) as cur:
            yield cur
    except Exception:
        try:
            conn.rollback()
        except Exception:
            pass
        raise
    finally:
        pool.putconn(conn)


def error_response(message: str, status_code: int):
    return jsonify({"message": message}), status_code


def require_json_object() -> dict:
    payload = request.get_json(silent=True)
    if not isinstance(payload, dict):
        raise ValidationError("Invalid JSON body")
    return payload


def validate_integer(value, field_name: str, required: bool = False):
    if value is None:
        if required:
            raise ValidationError(f"{field_name} is required")
        return None
    if isinstance(value, bool) or not isinstance(value, int):
        raise ValidationError(f"{field_name} must be an integer")
    return value


def validate_string(value, field_name: str, required: bool = False):
    if value is None:
        if required:
            raise ValidationError(f"{field_name} is required")
        return None
    if not isinstance(value, str):
        raise ValidationError(f"{field_name} must be a string")
    return value


def validate_boolean(value, field_name: str):
    if value is None:
        return None
    if not isinstance(value, bool):
        raise ValidationError(f"{field_name} must be a boolean")
    return value


def validate_string_list(value, field_name: str, required: bool = False):
    if value is None:
        if required:
            raise ValidationError(f"{field_name} is required")
        return None
    if not isinstance(value, list) or any(not isinstance(item, str) for item in value):
        raise ValidationError(f"{field_name} must be an array of strings")
    return value


def validate_enum(value, field_name: str, allowed_values: set[str]):
    if value is None:
        return None
    if not isinstance(value, str) or value not in allowed_values:
        raise ValidationError(f"{field_name} must be one of {sorted(allowed_values)}")
    return value


def parse_datetime(value, field_name: str):
    if value is None:
        return None
    if not isinstance(value, str):
        raise ValidationError(f"{field_name} must be a date-time string")
    try:
        normalized = value[:-1] + "+00:00" if value.endswith("Z") else value
        return datetime.fromisoformat(normalized)
    except ValueError as exc:
        raise ValidationError(f"{field_name} must be a valid date-time") from exc


def serialize_datetime(value: datetime | None):
    if value is None:
        return None
    iso_value = value.isoformat()
    return iso_value.replace("+00:00", "Z")


def serialize_pet(row: dict) -> dict:
    return {
        "id": row["id"],
        "name": row["name"],
        "photoUrls": row["photo_urls"],
        "status": row["status"],
    }


def serialize_order(row: dict) -> dict:
    return {
        "id": row["id"],
        "petId": row["pet_id"],
        "quantity": row["quantity"],
        "shipDate": serialize_datetime(row["ship_date"]),
        "status": row["status"],
        "complete": row["complete"],
    }


def serialize_user(row: dict) -> dict:
    return {
        "id": row["id"],
        "username": row["username"],
        "firstName": row["first_name"],
        "lastName": row["last_name"],
        "email": row["email"],
        "password": row["password"],
        "phone": row["phone"],
        "userStatus": row["user_status"],
    }


def normalize_pet(payload: dict, require_id: bool = False) -> dict:
    return {
        "id": validate_integer(payload.get("id"), "id", required=require_id),
        "name": validate_string(payload.get("name"), "name", required=True),
        "photo_urls": validate_string_list(payload.get("photoUrls"), "photoUrls", required=True),
        "status": validate_enum(payload.get("status"), "status", PET_STATUSES),
    }


def normalize_order(payload: dict) -> dict:
    return {
        "id": validate_integer(payload.get("id"), "id"),
        "pet_id": validate_integer(payload.get("petId"), "petId"),
        "quantity": validate_integer(payload.get("quantity"), "quantity"),
        "ship_date": parse_datetime(payload.get("shipDate"), "shipDate"),
        "status": validate_enum(payload.get("status"), "status", ORDER_STATUSES),
        "complete": validate_boolean(payload.get("complete"), "complete"),
    }


def normalize_user(payload: dict, require_username: bool = False) -> dict:
    return {
        "id": validate_integer(payload.get("id"), "id"),
        "username": validate_string(payload.get("username"), "username", required=require_username),
        "first_name": validate_string(payload.get("firstName"), "firstName"),
        "last_name": validate_string(payload.get("lastName"), "lastName"),
        "email": validate_string(payload.get("email"), "email"),
        "password": validate_string(payload.get("password"), "password"),
        "phone": validate_string(payload.get("phone"), "phone"),
        "user_status": validate_integer(payload.get("userStatus"), "userStatus"),
    }


def handle_write_error(exc: Exception):
    if isinstance(exc, (errors.UniqueViolation, errors.CheckViolation, errors.NotNullViolation)):
        return error_response("Invalid input", 400)
    raise exc


@app.post("/pet")
def add_pet():
    try:
        pet = normalize_pet(require_json_object())
        with get_cursor() as cur:
            if pet["id"] is None:
                cur.execute(
                    """
                    INSERT INTO pets (name, photo_urls, status)
                    VALUES (%s, %s, %s)
                    RETURNING id, name, photo_urls, status
                    """,
                    (pet["name"], pet["photo_urls"], pet["status"]),
                )
            else:
                cur.execute(
                    """
                    INSERT INTO pets (id, name, photo_urls, status)
                    VALUES (%s, %s, %s, %s)
                    RETURNING id, name, photo_urls, status
                    """,
                    (pet["id"], pet["name"], pet["photo_urls"], pet["status"]),
                )
            return jsonify(serialize_pet(cur.fetchone()))
    except ValidationError as exc:
        return error_response(str(exc), 400)
    except Exception as exc:
        if isinstance(exc, psycopg2.Error):
            return handle_write_error(exc)
        raise


