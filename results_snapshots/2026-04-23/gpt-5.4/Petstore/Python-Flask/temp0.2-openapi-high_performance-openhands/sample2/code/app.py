@app.put("/user/<string:username>")
def update_user(username):
    try:
        incoming = validate_user(get_json_body())
    except ValueError as exc:
        return error_response(str(exc), 400)

    existing = execute(
        "SELECT id, username, first_name, last_name, email, password, phone, user_status FROM users WHERE username = %s",
        (username,),
        fetchone=True,
    )
    if existing is None:
        return error_response("User not found", 404)

    current = serialize_user(existing)
    updated = {
        "id": incoming["id"] if incoming["id"] is not None else current["id"],
        "username": incoming["username"] if incoming["username"] is not None else current["username"],
        "firstName": incoming["firstName"] if incoming["firstName"] is not None else current["firstName"],
        "lastName": incoming["lastName"] if incoming["lastName"] is not None else current["lastName"],
        "email": incoming["email"] if incoming["email"] is not None else current["email"],
        "password": incoming["password"] if incoming["password"] is not None else current["password"],
        "phone": incoming["phone"] if incoming["phone"] is not None else current["phone"],
        "userStatus": incoming["userStatus"] if incoming["userStatus"] is not None else current["userStatus"],
    }

    try:
        row = execute(
            """
            UPDATE users
            SET id = %s,
                username = %s,
                first_name = %s,
                last_name = %s,
                email = %s,
                password = %s,
                phone = %s,
                user_status = %s
            WHERE username = %s
            RETURNING id, username, first_name, last_name, email, password, phone, user_status
            """,
            (
                updated["id"],
                updated["username"],
                updated["firstName"],
                updated["lastName"],
                updated["email"],
                updated["password"],
                updated["phone"],
                updated["userStatus"],
                username,
            ),
            fetchone=True,
        )
        return jsonify(serialize_user(row))
    except IntegrityError:
        return error_response("Invalid input", 400)


