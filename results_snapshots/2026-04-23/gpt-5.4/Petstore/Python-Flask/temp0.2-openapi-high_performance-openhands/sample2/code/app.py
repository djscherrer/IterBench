import os
import threading
from datetime import datetime

import psycopg2
from flask import Flask, jsonify, request
from psycopg2 import IntegrityError
from psycopg2.pool import ThreadedConnectionPool

app = Flask(__name__)
app.config["JSON_SORT_KEYS"] = False

PET_STATUSES = frozenset({"available", "pending", "sold"})
ORDER_STATUSES = frozenset({"placed", "approved", "delivered"})
INIT_LOCK_ID = 721438905421337114

SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS pets (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    photo_urls TEXT[] NOT NULL DEFAULT '{}',
    status TEXT NOT NULL DEFAULT 'available',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pets_status_check CHECK (status IN ('available', 'pending', 'sold'))
);

CREATE INDEX IF NOT EXISTS idx_pets_status_id ON pets (status, id);

CREATE TABLE IF NOT EXISTS orders (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    pet_id BIGINT,
    quantity INTEGER,
    ship_date TIMESTAMPTZ,
    status TEXT,
    complete BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT orders_status_check CHECK (status IS NULL OR status IN ('placed', 'approved', 'delivered'))
);

CREATE INDEX IF NOT EXISTS idx_orders_pet_id ON orders (pet_id);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    username TEXT NOT NULL UNIQUE,
    first_name TEXT,
    last_name TEXT,
    email TEXT,
    password TEXT,
    phone TEXT,
    user_status INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
"""

_pool = None
_pool_pid = None
_pool_lock = threading.Lock()
_db_config = None


def get_db_config():
    global _db_config
    if _db_config is None:
        required = ("DB_HOST", "DB_PORT", "DB_USER", "DB_PASSWORD", "DB_NAME")
        missing = [name for name in required if not os.getenv(name)]
        if missing:
            raise RuntimeError(f"Missing database environment variables: {', '.join(missing)}")

        base_config = {
            "host": os.environ["DB_HOST"],
            "port": int(os.environ["DB_PORT"]),
            "user": os.environ["DB_USER"],
            "password": os.environ["DB_PASSWORD"],
            "dbname": os.environ["DB_NAME"],
            "connect_timeout": 5,
            "application_name": "petstore_api",
        }

        candidates = [base_config["host"]]
        if base_config["host"] not in {"localhost", "127.0.0.1"}:
            candidates.extend(["localhost", "127.0.0.1"])

        last_error = None
        for host in candidates:
            candidate = dict(base_config)
            candidate["host"] = host
            try:
                conn = psycopg2.connect(**candidate)
            except psycopg2.OperationalError as exc:
                last_error = exc
            else:
                conn.close()
                _db_config = candidate
                break

        if _db_config is None:
            raise last_error
    return _db_config


def initialize_database():
    conn = psycopg2.connect(**get_db_config())
    try:
        with conn:
            with conn.cursor() as cur:
                cur.execute("SELECT pg_advisory_lock(%s)", (INIT_LOCK_ID,))
                try:
                    cur.execute(SCHEMA_SQL)
                finally:
                    cur.execute("SELECT pg_advisory_unlock(%s)", (INIT_LOCK_ID,))
    finally:
        conn.close()


def get_pool():
    global _pool, _pool_pid
    pid = os.getpid()
    if _pool is None or _pool_pid != pid:
        with _pool_lock:
            if _pool is None or _pool_pid != pid:
                if _pool is not None:
                    try:
                        _pool.closeall()
                    except Exception:
                        pass
                minconn = max(1, int(os.getenv("DB_POOL_MIN", "1")))
                maxconn = max(minconn, int(os.getenv("DB_POOL_MAX", "8")))
                _pool = ThreadedConnectionPool(minconn, maxconn, **get_db_config())
                _pool_pid = pid
    return _pool


def execute(query, params=(), *, fetchone=False, fetchall=False):
    pool = get_pool()
    conn = pool.getconn()
    try:
        with conn.cursor() as cur:
            cur.execute(query, params)
            result = None
            if fetchone:
                result = cur.fetchone()
            elif fetchall:
                result = cur.fetchall()
        conn.commit()
        return result
    except Exception:
        conn.rollback()
        raise
    finally:
        pool.putconn(conn)


def is_int(value):
    return isinstance(value, int) and not isinstance(value, bool)


def parse_datetime_value(value):
    if value is None:
        return None
    if not isinstance(value, str):
        raise ValueError("shipDate must be a string")
    candidate = value.strip()
    if not candidate:
        raise ValueError("shipDate must not be empty")
    try:
        return datetime.fromisoformat(candidate.replace("Z", "+00:00"))
    except ValueError as exc:
        raise ValueError("shipDate must be a valid date-time") from exc


def isoformat_value(value):
    return value.isoformat() if value is not None else None


def get_json_body():
    payload = request.get_json(silent=True)
    if not isinstance(payload, dict):
        raise ValueError("Request body must be a JSON object")
    return payload


def error_response(message, status_code):
    return jsonify({"message": message}), status_code


def serialize_pet(row):
    return {
        "id": row[0],
        "name": row[1],
        "photoUrls": row[2] or [],
        "status": row[3],
    }


def serialize_order(row):
    return {
        "id": row[0],
        "petId": row[1],
        "quantity": row[2],
        "shipDate": isoformat_value(row[3]),
        "status": row[4],
        "complete": row[5],
    }


def serialize_user(row):
    return {
        "id": row[0],
        "username": row[1],
        "firstName": row[2],
        "lastName": row[3],
        "email": row[4],
        "password": row[5],
        "phone": row[6],
        "userStatus": row[7],
    }


def validate_pet(payload, *, require_id=False):
    pet_id = payload.get("id")
    if pet_id is not None and not is_int(pet_id):
        raise ValueError("id must be an integer")
    if require_id and pet_id is None:
        raise ValueError("id is required")

    name = payload.get("name")
    if not isinstance(name, str):
        raise ValueError("name is required")

    photo_urls = payload.get("photoUrls")
    if not isinstance(photo_urls, list) or any(not isinstance(item, str) for item in photo_urls):
        raise ValueError("photoUrls must be an array of strings")

    status = payload.get("status", "available")
    if status is None:
        status = "available"
    if not isinstance(status, str) or status not in PET_STATUSES:
        raise ValueError("status must be one of: available, pending, sold")

    return {
        "id": pet_id,
        "name": name,
        "photoUrls": photo_urls,
        "status": status,
    }


def validate_order(payload):
    order_id = payload.get("id")
    if order_id is not None and not is_int(order_id):
        raise ValueError("id must be an integer")

    pet_id = payload.get("petId")
    if pet_id is not None and not is_int(pet_id):
        raise ValueError("petId must be an integer")

    quantity = payload.get("quantity")
    if quantity is not None and not is_int(quantity):
        raise ValueError("quantity must be an integer")

    status = payload.get("status")
    if status is not None:
        if not isinstance(status, str) or status not in ORDER_STATUSES:
            raise ValueError("status must be one of: placed, approved, delivered")

    complete = payload.get("complete")
    if complete is not None and not isinstance(complete, bool):
        raise ValueError("complete must be a boolean")

    return {
        "id": order_id,
        "petId": pet_id,
        "quantity": quantity,
        "shipDate": parse_datetime_value(payload.get("shipDate")),
        "status": status,
        "complete": False if complete is None else complete,
    }


def validate_user(payload, *, require_username=False):
    user_id = payload.get("id")
    if user_id is not None and not is_int(user_id):
        raise ValueError("id must be an integer")

    username = payload.get("username")
    if require_username and not isinstance(username, str):
        raise ValueError("username is required")
    if username is not None and not isinstance(username, str):
        raise ValueError("username must be a string")

    for field in ("firstName", "lastName", "email", "password", "phone"):
        value = payload.get(field)
        if value is not None and not isinstance(value, str):
            raise ValueError(f"{field} must be a string")

    user_status = payload.get("userStatus")
    if user_status is not None and not is_int(user_status):
        raise ValueError("userStatus must be an integer")

    return {
        "id": user_id,
        "username": username,
        "firstName": payload.get("firstName"),
        "lastName": payload.get("lastName"),
        "email": payload.get("email"),
        "password": payload.get("password"),
        "phone": payload.get("phone"),
        "userStatus": user_status,
    }


@app.post("/pet")
def add_pet():
    try:
        pet = validate_pet(get_json_body())
        if pet["id"] is None:
            row = execute(
                """
                INSERT INTO pets (name, photo_urls, status)
                VALUES (%s, %s, %s)
                RETURNING id, name, photo_urls, status
                """,
                (pet["name"], pet["photoUrls"], pet["status"]),
                fetchone=True,
            )
        else:
            row = execute(
                """
                INSERT INTO pets (id, name, photo_urls, status)
                VALUES (%s, %s, %s, %s)
                RETURNING id, name, photo_urls, status
                """,
                (pet["id"], pet["name"], pet["photoUrls"], pet["status"]),
                fetchone=True,
            )
        return jsonify(serialize_pet(row))
    except ValueError as exc:
        return error_response(str(exc), 400)
    except IntegrityError:
        return error_response("Invalid input", 400)


