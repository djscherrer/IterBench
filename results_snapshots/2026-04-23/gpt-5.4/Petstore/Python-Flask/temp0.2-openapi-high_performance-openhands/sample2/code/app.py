@app.get("/pet/findByStatus")
def find_pets_by_status():
    status = request.args.get("status")
    if status not in PET_STATUSES:
        return error_response("Invalid status", 400)
    rows = execute(
        "SELECT id, name, photo_urls, status FROM pets WHERE status = %s ORDER BY id",
        (status,),
        fetchall=True,
    )
    return jsonify([serialize_pet(row) for row in rows])


