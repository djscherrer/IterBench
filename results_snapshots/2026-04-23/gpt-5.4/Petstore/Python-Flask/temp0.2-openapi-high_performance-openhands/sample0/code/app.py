@app.post("/user")
def create_user():
    data = get_json_body()
    error = validate_user(data, require_username=True)
    if error:
        return json_error(error, 400)

    columns = ["username"]
    values = [data["username"]]
    updatable_columns = []

    for column, key in (
        ("id", "id"),
        ("first_name", "firstName"),
        ("last_name", "lastName"),
        ("email", "email"),
        ("password", "password"),
        ("phone", "phone"),
        ("user_status", "userStatus"),
    ):
        if key in data:
            columns.append(column)
            values.append(data.get(key))
            updatable_columns.append(column)

    update_assignments = ", ".join(f"{column} = EXCLUDED.{column}" for column in updatable_columns)
    sql = f"""
        INSERT INTO users ({', '.join(columns)})
        VALUES ({', '.join(['%s'] * len(values))})
        ON CONFLICT (username) DO UPDATE
        SET {update_assignments if update_assignments else 'username = EXCLUDED.username'}
        RETURNING username, id, first_name, last_name, email, password, phone, user_status
    """
    try:
        with db.connection() as conn, conn.cursor() as cursor:
            cursor.execute(sql, values)
            row = cursor.fetchone()
    except psycopg2.Error:
        return json_error("Invalid input", 400)
    return jsonify(user_to_dict(row))


