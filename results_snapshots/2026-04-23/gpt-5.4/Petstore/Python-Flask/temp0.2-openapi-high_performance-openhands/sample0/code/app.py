SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS pets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    photo_urls TEXT[] NOT NULL,
    status TEXT CHECK (status IN ('available', 'pending', 'sold'))
);

CREATE INDEX IF NOT EXISTS idx_pets_status ON pets (status);

CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id BIGINT,
    quantity INTEGER,
    ship_date TIMESTAMPTZ,
    status TEXT CHECK (status IN ('placed', 'approved', 'delivered')),
    complete BOOLEAN
);

CREATE INDEX IF NOT EXISTS idx_orders_pet_id ON orders (pet_id);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders (status);

CREATE TABLE IF NOT EXISTS users (
    username TEXT PRIMARY KEY,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    first_name TEXT,
    last_name TEXT,
    email TEXT,
    password TEXT,
    phone TEXT,
    user_status INTEGER
);
"""


class Database:
    def __init__(self):
        self._pool = None
        self._pool_pid = None
        self._lock = threading.Lock()
        os.register_at_fork(after_in_child=self._after_fork)
        atexit.register(self.close)

    def _after_fork(self):
        self._pool = None
        self._pool_pid = None

    def initialize_schema(self):
        conn = psycopg2.connect(**_db_config())
        try:
            conn.autocommit = True
            with conn.cursor() as cursor:
                cursor.execute(SCHEMA_SQL)
        finally:
            conn.close()

    def _ensure_pool(self):
        current_pid = os.getpid()
        if self._pool is not None and self._pool_pid == current_pid:
            return
        with self._lock:
            if self._pool is not None and self._pool_pid == current_pid:
                return
            if self._pool is not None:
                try:
                    self._pool.closeall()
                except Exception:
                    pass
            self._pool = ThreadedConnectionPool(1, MAX_DB_CONNECTIONS, **_db_config())
            self._pool_pid = current_pid

    @contextmanager
    def connection(self):
        self._ensure_pool()
        conn = self._pool.getconn()
        try:
            if not conn.autocommit:
                conn.autocommit = True
            yield conn
        finally:
            self._pool.putconn(conn)

    def close(self):
        if self._pool is not None:
            try:
                self._pool.closeall()
            except Exception:
                pass
            self._pool = None
            self._pool_pid = None


db = Database()
db.initialize_schema()


def pet_to_dict(row):
    return {
        "id": row[0],
        "name": row[1],
        "photoUrls": row[2],
        "status": row[3],
    }


def order_to_dict(row):
    return {
        "id": row[0],
        "petId": row[1],
        "quantity": row[2],
        "shipDate": row[3].isoformat().replace("+00:00", "Z") if row[3] is not None else None,
        "status": row[4],
        "complete": row[5],
    }


def user_to_dict(row):
    return {
        "username": row[0],
        "id": row[1],
        "firstName": row[2],
        "lastName": row[3],
        "email": row[4],
        "password": row[5],
        "phone": row[6],
        "userStatus": row[7],
    }


def json_error(message, status_code):
    return jsonify({"message": message}), status_code


def get_json_body():
    data = request.get_json(silent=True)
    if not isinstance(data, dict):
        return None
    return data


def validate_pet(data, require_id=False):
    if data is None:
        return "Invalid input"
    if require_id and data.get("id") is None:
        return "Pet id is required"
    if "name" not in data or not isinstance(data.get("name"), str) or not data.get("name"):
        return "Pet name is required"
    photo_urls = data.get("photoUrls")
    if not isinstance(photo_urls, list) or any(not isinstance(item, str) for item in photo_urls):
        return "photoUrls must be an array of strings"
    status = data.get("status")
    if status is not None and status not in PET_STATUSES:
        return "Invalid pet status"
    return None


def validate_order(data):
    if data is None:
        return "Invalid input"
    if data.get("petId") is not None and not isinstance(data.get("petId"), int):
        return "petId must be an integer"
    if data.get("quantity") is not None and not isinstance(data.get("quantity"), int):
        return "quantity must be an integer"
    if data.get("complete") is not None and not isinstance(data.get("complete"), bool):
        return "complete must be a boolean"
    status = data.get("status")
    if status is not None and status not in ORDER_STATUSES:
        return "Invalid order status"
    return None


def validate_user(data, require_username=False):
    if data is None:
        return "Invalid input"
    if require_username and (not isinstance(data.get("username"), str) or not data.get("username")):
        return "username is required"
    if data.get("username") is not None and not isinstance(data.get("username"), str):
        return "username must be a string"
    if data.get("id") is not None and not isinstance(data.get("id"), int):
        return "id must be an integer"
    if data.get("userStatus") is not None and not isinstance(data.get("userStatus"), int):
        return "userStatus must be an integer"
    return None


@app.post("/pet")
def add_pet():
    data = get_json_body()
    error = validate_pet(data)
    if error:
        return json_error(error, 400)

    columns = ["name", "photo_urls", "status"]
    values = [data["name"], data["photoUrls"], data.get("status")]
    if data.get("id") is not None:
        columns.insert(0, "id")
        values.insert(0, data["id"])

    sql = f"""
        INSERT INTO pets ({', '.join(columns)})
        VALUES ({', '.join(['%s'] * len(values))})
        RETURNING id, name, photo_urls, status
    """
    try:
        with db.connection() as conn, conn.cursor() as cursor:
            cursor.execute(sql, values)
            row = cursor.fetchone()
    except psycopg2.Error:
        return json_error("Invalid input", 400)
    return jsonify(pet_to_dict(row))


