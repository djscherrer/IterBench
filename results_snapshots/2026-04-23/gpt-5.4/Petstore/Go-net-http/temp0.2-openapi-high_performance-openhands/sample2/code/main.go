func scanOrder(row *sql.Row) (Order, error) {
	var order Order
	var shipDate sql.NullTime
	if err := row.Scan(&order.ID, &order.PetID, &order.Quantity, &shipDate, &order.Status, &order.Complete); err != nil {
		return Order{}, err
	}
	if shipDate.Valid {
		t := shipDate.Time.UTC()
		order.ShipDate = &t
	}
	return order, nil
}

func scanUser(row *sql.Row) (User, error) {
	var user User
	err := row.Scan(&user.ID, &user.Username, &user.FirstName, &user.LastName, &user.Email, &user.Password, &user.Phone, &user.UserStatus)
	return user, err
}

func decodeJSON(w http.ResponseWriter, r *http.Request, dst any) error {
	r.Body = http.MaxBytesReader(w, r.Body, maxBodyBytes)
	defer r.Body.Close()

	dec := json.NewDecoder(r.Body)
	dec.DisallowUnknownFields()
	if err := dec.Decode(dst); err != nil {
		if errors.Is(err, io.EOF) {
			return errors.New("request body is required")
		}
		return fmt.Errorf("invalid request body: %w", err)
	}

	var extra any
	if err := dec.Decode(&extra); err != io.EOF {
		return errors.New("request body must contain a single JSON value")
	}
	return nil
}

func writeJSON(w http.ResponseWriter, status int, value any) {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(status)
	enc := json.NewEncoder(w)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(value)
}

func handleDBError(w http.ResponseWriter, err error) {
	var pqErr *pq.Error
	if errors.As(err, &pqErr) {
		switch pqErr.Code {
		case "23502", "23505", "23514", "22P02":
			http.Error(w, "invalid input", http.StatusBadRequest)
			return
		}
	}
	http.Error(w, "internal server error", http.StatusInternalServerError)
}

func validatePet(pet *Pet) error {
	pet.Name = strings.TrimSpace(pet.Name)
	if pet.Name == "" {
		return errors.New("name is required")
	}
	if pet.PhotoURLs == nil {
		return errors.New("photoUrls is required")
	}
	if pet.Status == "" {
		pet.Status = "available"
	}
	if !isValidPetStatus(pet.Status) {
		return errors.New("invalid status")
	}
	return nil
}

func validateOrder(order *Order) error {
	if order.Status == "" {
		order.Status = "placed"
	}
	if !isValidOrderStatus(order.Status) {
		return errors.New("invalid status")
	}
	if order.Quantity < 0 {
		return errors.New("quantity must be non-negative")
	}
	return nil
}

func validateCreateUser(user *User) error {
	user.Username = strings.TrimSpace(user.Username)
	if user.Username == "" {
		return errors.New("username is required")
	}
	return nil
}

func isValidPetStatus(status string) bool {
	switch status {
	case "available", "pending", "sold":
		return true
	default:
		return false
	}
}

func isValidOrderStatus(status string) bool {
	switch status {
	case "placed", "approved", "delivered":
		return true
	default:
		return false
	}
}

func parseIDParam(value string) (int64, error) {
	id, err := strconv.ParseInt(value, 10, 64)
	if err != nil || id <= 0 {
		return 0, errors.New("invalid id")
	}
	return id, nil
}

func timeArg(value *time.Time) any {
	if value == nil {
		return nil
	}
	return value.UTC()
}

func envOrDefault(key, fallback string) string {
	if value, ok := os.LookupEnv(key); ok && strings.TrimSpace(value) != "" {
		return value
	}
	return fallback
}

func requireEnv(key string) (string, error) {
	value, ok := os.LookupEnv(key)
	if !ok || strings.TrimSpace(value) == "" {
		return "", fmt.Errorf("%s is required", key)
	}
	return value, nil
}
