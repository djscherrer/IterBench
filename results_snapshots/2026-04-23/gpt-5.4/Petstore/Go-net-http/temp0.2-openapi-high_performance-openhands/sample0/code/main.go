func (a *app) loginUser(w http.ResponseWriter, r *http.Request) {
	username := strings.TrimSpace(r.URL.Query().Get("username"))
	password := r.URL.Query().Get("password")
	if username == "" || password == "" {
		http.Error(w, "username and password are required", http.StatusBadRequest)
		return
	}

	ctx, cancel := a.dbContext()
	defer cancel()

	var valid bool
	if err := a.db.QueryRowContext(ctx, `
SELECT EXISTS(
    SELECT 1
    FROM users
    WHERE username = $1 AND password = $2
)`, username, password).Scan(&valid); err != nil {
		writeDBError(w, err, http.StatusInternalServerError)
		return
	}
	if !valid {
		http.Error(w, "Invalid credentials", http.StatusBadRequest)
		return
	}

	writeJSON(w, http.StatusOK, "logged in user session")
}

func validatePet(pet *Pet, requireCoreFields bool) error {
	pet.Name = strings.TrimSpace(pet.Name)
	if requireCoreFields && pet.Name == "" {
		return errors.New("name is required")
	}
	if requireCoreFields && pet.PhotoURLs == nil {
		return errors.New("photoUrls is required")
	}
	status, err := normalizePetStatus(pet.Status)
	if err != nil {
		return err
	}
	pet.Status = status
	return nil
}

func validateOrder(order *Order) error {
	status, err := normalizeOrderStatus(order.Status)
	if err != nil {
		return err
	}
	order.Status = status
	return nil
}

func validateUser(user *User) error {
	user.Username = strings.TrimSpace(user.Username)
	if user.Username == "" {
		return errors.New("username is required")
	}
	return nil
}

func normalizePetStatus(status string) (string, error) {
	status = strings.ToLower(strings.TrimSpace(status))
	if status == "" {
		return "available", nil
	}
	if _, ok := validPetStatuses[status]; !ok {
		return "", errors.New("invalid pet status")
	}
	return status, nil
}

func normalizeOrderStatus(status string) (string, error) {
	status = strings.ToLower(strings.TrimSpace(status))
	if status == "" {
		return "placed", nil
	}
	if _, ok := validOrderStatuses[status]; !ok {
		return "", errors.New("invalid order status")
	}
	return status, nil
}

func scanPet(scanner interface{ Scan(...any) error }, pet *Pet) error {
	var id int64
	var photoURLs []string
	if err := scanner.Scan(&id, &pet.Name, pq.Array(&photoURLs), &pet.Status); err != nil {
		return err
	}
	pet.ID = &id
	pet.PhotoURLs = photoURLs
	return nil
}

func scanOrder(scanner interface{ Scan(...any) error }, order *Order) error {
	var id int64
	var shipDate sql.NullTime
	if err := scanner.Scan(&id, &order.PetID, &order.Quantity, &shipDate, &order.Status, &order.Complete); err != nil {
		return err
	}
	order.ID = &id
	if shipDate.Valid {
		t := shipDate.Time.UTC()
		order.ShipDate = &t
	} else {
		order.ShipDate = nil
	}
	return nil
}

func scanUser(scanner interface{ Scan(...any) error }, user *User) error {
	var id int64
	if err := scanner.Scan(&id, &user.Username, &user.FirstName, &user.LastName, &user.Email, &user.Password, &user.Phone, &user.UserStatus); err != nil {
		return err
	}
	user.ID = &id
	return nil
}

func parsePathInt64(w http.ResponseWriter, r *http.Request, key string) (int64, bool) {
	value := strings.TrimSpace(r.PathValue(key))
	parsed, err := strconv.ParseInt(value, 10, 64)
	if err != nil {
		http.Error(w, "invalid "+key, http.StatusBadRequest)
		return 0, false
	}
	return parsed, true
}

func decodeJSON(w http.ResponseWriter, r *http.Request, dst any) bool {
	r.Body = http.MaxBytesReader(w, r.Body, maxBodyBytes)
	defer r.Body.Close()

	decoder := json.NewDecoder(r.Body)
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(dst); err != nil {
		http.Error(w, "invalid JSON body", http.StatusBadRequest)
		return false
	}
	if err := decoder.Decode(&struct{}{}); err != io.EOF {
		http.Error(w, "invalid JSON body", http.StatusBadRequest)
		return false
	}
	return true
}

func writeJSON(w http.ResponseWriter, status int, value any) {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(status)
	if err := json.NewEncoder(w).Encode(value); err != nil {
		log.Printf("write JSON response: %v", err)
	}
}

func writeDBError(w http.ResponseWriter, err error, fallbackStatus int) {
	if isClientDBError(err) {
		http.Error(w, "Invalid input", http.StatusBadRequest)
		return
	}
	http.Error(w, http.StatusText(fallbackStatus), fallbackStatus)
}

func isClientDBError(err error) bool {
	var pgErr *pq.Error
	if !errors.As(err, &pgErr) {
		return false
	}
	switch pgErr.Code {
	case "22007", "22P02", "23502", "23505", "23514":
		return true
	default:
		return false
	}
}

func getenv(key, fallback string) string {
	if value := os.Getenv(key); value != "" {
		return value
	}
	return fallback
}
