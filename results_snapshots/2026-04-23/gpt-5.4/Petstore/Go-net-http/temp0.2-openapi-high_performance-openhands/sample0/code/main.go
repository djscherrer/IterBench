func main() {
	db, err := openDB()
	if err != nil {
		log.Fatalf("open database: %v", err)
	}
	defer db.Close()

	if err := initDB(db); err != nil {
		log.Fatalf("initialize database: %v", err)
	}

	application := &app{db: db}
	mux := http.NewServeMux()
	mux.HandleFunc("POST /pet", application.addPet)
	mux.HandleFunc("PUT /pet", application.updatePet)
	mux.HandleFunc("GET /pet/findByStatus", application.findPetsByStatus)
	mux.HandleFunc("GET /pet/{petId}", application.getPetByID)
	mux.HandleFunc("DELETE /pet/{petId}", application.deletePet)
	mux.HandleFunc("POST /store/order", application.placeOrder)
	mux.HandleFunc("GET /store/order/{orderId}", application.getOrderByID)
	mux.HandleFunc("DELETE /store/order/{orderId}", application.deleteOrder)
	mux.HandleFunc("POST /user", application.createUser)
	mux.HandleFunc("GET /user/login", application.loginUser)
	mux.HandleFunc("GET /user/{username}", application.getUserByName)
	mux.HandleFunc("PUT /user/{username}", application.updateUser)
	mux.HandleFunc("DELETE /user/{username}", application.deleteUser)

	port := getenv("PORT", "5001")
	server := &http.Server{
		Addr:              "0.0.0.0:" + port,
		Handler:           mux,
		ReadHeaderTimeout: 2 * time.Second,
		ReadTimeout:       10 * time.Second,
		WriteTimeout:      15 * time.Second,
		IdleTimeout:       60 * time.Second,
		MaxHeaderBytes:    1 << 20,
	}

	log.Printf("listening on %s", server.Addr)
	if err := server.ListenAndServe(); err != nil && !errors.Is(err, http.ErrServerClosed) {
		log.Fatalf("serve: %v", err)
	}
}

func openDB() (*sql.DB, error) {
	host := os.Getenv("DB_HOST")
	user := os.Getenv("DB_USER")
	dbName := os.Getenv("DB_NAME")
	if host == "" || user == "" || dbName == "" {
		return nil, errors.New("DB_HOST, DB_USER, and DB_NAME must be set")
	}

	dsn := fmt.Sprintf(
		"host=%s port=%s user=%s password=%s dbname=%s sslmode=disable application_name=petstore_api",
		host,
		getenv("DB_PORT", "5432"),
		user,
		os.Getenv("DB_PASSWORD"),
		dbName,
	)

	db, err := sql.Open("postgres", dsn)
	if err != nil {
		return nil, err
	}

	maxOpenConns := runtime.GOMAXPROCS(0) * 16
	if maxOpenConns < 32 {
		maxOpenConns = 32
	}
	db.SetMaxOpenConns(maxOpenConns)
	db.SetMaxIdleConns(maxOpenConns)
	db.SetConnMaxIdleTime(5 * time.Minute)
	db.SetConnMaxLifetime(30 * time.Minute)

	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	if err := db.PingContext(ctx); err != nil {
		db.Close()
		return nil, err
	}

	return db, nil
}

func initDB(db *sql.DB) error {
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()

	const schema = `
CREATE TABLE IF NOT EXISTS pets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    photo_urls TEXT[] NOT NULL,
    status TEXT NOT NULL DEFAULT 'available' CHECK (status IN ('available', 'pending', 'sold'))
);
CREATE INDEX IF NOT EXISTS idx_pets_status ON pets (status);

CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id BIGINT NOT NULL DEFAULT 0,
    quantity INTEGER NOT NULL DEFAULT 0,
    ship_date TIMESTAMPTZ,
    status TEXT NOT NULL DEFAULT 'placed' CHECK (status IN ('placed', 'approved', 'delivered')),
    complete BOOLEAN NOT NULL DEFAULT false
);
CREATE INDEX IF NOT EXISTS idx_orders_pet_id ON orders (pet_id);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    username TEXT PRIMARY KEY,
    first_name TEXT NOT NULL DEFAULT '',
    last_name TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL DEFAULT '',
    password TEXT NOT NULL DEFAULT '',
    phone TEXT NOT NULL DEFAULT '',
    user_status INTEGER NOT NULL DEFAULT 0
);
`

	_, err := db.ExecContext(ctx, schema)
	return err
}

func (a *app) dbContext() (context.Context, context.CancelFunc) {
	return context.WithTimeout(context.Background(), 5*time.Second)
}

func (a *app) addPet(w http.ResponseWriter, r *http.Request) {
	var pet Pet
	if !decodeJSON(w, r, &pet) {
		return
	}
	if err := validatePet(&pet, true); err != nil {
		http.Error(w, err.Error(), http.StatusBadRequest)
		return
	}

	ctx, cancel := a.dbContext()
	defer cancel()

	var row *sql.Row
	if pet.ID != nil {
		row = a.db.QueryRowContext(ctx, `
INSERT INTO pets (id, name, photo_urls, status)
VALUES ($1, $2, $3, $4)
RETURNING id, name, photo_urls, status`, *pet.ID, pet.Name, pq.Array(pet.PhotoURLs), pet.Status)
	} else {
		row = a.db.QueryRowContext(ctx, `
INSERT INTO pets (name, photo_urls, status)
VALUES ($1, $2, $3)
RETURNING id, name, photo_urls, status`, pet.Name, pq.Array(pet.PhotoURLs), pet.Status)
	}

	if err := scanPet(row, &pet); err != nil {
		writeDBError(w, err, http.StatusBadRequest)
		return
	}
	writeJSON(w, http.StatusOK, pet)
}

func (a *app) updatePet(w http.ResponseWriter, r *http.Request) {
	var pet Pet
	if !decodeJSON(w, r, &pet) {
		return
	}
	if pet.ID == nil {
		http.Error(w, "id is required", http.StatusBadRequest)
		return
	}
	if err := validatePet(&pet, true); err != nil {
		http.Error(w, err.Error(), http.StatusBadRequest)
		return
	}

	ctx, cancel := a.dbContext()
	defer cancel()

	row := a.db.QueryRowContext(ctx, `
UPDATE pets
SET name = $2, photo_urls = $3, status = $4
WHERE id = $1
RETURNING id, name, photo_urls, status`, *pet.ID, pet.Name, pq.Array(pet.PhotoURLs), pet.Status)
	if err := scanPet(row, &pet); err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			http.Error(w, "Pet not found", http.StatusNotFound)
			return
		}
		writeDBError(w, err, http.StatusBadRequest)
		return
	}

	writeJSON(w, http.StatusOK, pet)
}

func (a *app) findPetsByStatus(w http.ResponseWriter, r *http.Request) {
	rawStatus := strings.TrimSpace(r.URL.Query().Get("status"))
	if rawStatus == "" {
		http.Error(w, "status is required", http.StatusBadRequest)
		return
	}
	status, err := normalizePetStatus(rawStatus)
	if err != nil {
		http.Error(w, err.Error(), http.StatusBadRequest)
		return
	}

	ctx, cancel := a.dbContext()
	defer cancel()

	rows, err := a.db.QueryContext(ctx, `
SELECT id, name, photo_urls, status
FROM pets
WHERE status = $1
ORDER BY id`, status)
	if err != nil {
		writeDBError(w, err, http.StatusInternalServerError)
		return
	}
	defer rows.Close()

	pets := make([]Pet, 0, 16)
	for rows.Next() {
		var pet Pet
		var id int64
		var photoURLs []string
		if err := rows.Scan(&id, &pet.Name, pq.Array(&photoURLs), &pet.Status); err != nil {
			writeDBError(w, err, http.StatusInternalServerError)
			return
		}
		pet.ID = &id
		pet.PhotoURLs = photoURLs
		pets = append(pets, pet)
	}
	if err := rows.Err(); err != nil {
		writeDBError(w, err, http.StatusInternalServerError)
		return
	}

	writeJSON(w, http.StatusOK, pets)
}

